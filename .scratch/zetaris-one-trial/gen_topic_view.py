"""Generate 02_criterion_topic.sql: the Criterion topic dictionary as a Zetaris view over our Postgres `criterion` table.

One dictionary drives both the discovery figures and Zetaris: CATEGORIES comes from
ctgov-discovery/scripts/04_mine_terms.py. FIXES patches known false positives before export:
  - eGFR is matched case-sensitively, so the EGFR gene no longer tags labs_organ_function.

Topics only route a Criterion to a checker; they are never cited as evidence.

Usage: python3 .scratch/zetaris-one-trial/gen_topic_view.py   → writes 02_criterion_topic.sql next to this file
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "ctgov-discovery" / "scripts"))   # 04_mine_terms imports ctgov_http
_spec = importlib.util.spec_from_file_location("mine", HERE.parent / "ctgov-discovery" / "scripts" / "04_mine_terms.py")
mine = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mine)

FIXES: dict[str, tuple[str, str]] = {
    "labs_organ_function": ("|eGFR|", "|(?-i:eGFR)|"),
}


def topics() -> dict[str, str]:
    """Topic → regex (Python and Java syntax), with FIXES applied and case-insensitivity made explicit."""
    out = {}
    for name, rx in mine.CATEGORIES.items():
        if name in FIXES:
            old, new = FIXES[name]
            assert old in rx, f"fix for {name} no longer applies"
            rx = rx.replace(old, new)
        out[name] = "(?i)" + rx
    return out


def compiled() -> dict[str, re.Pattern]:
    return {k: re.compile(v) for k, v in topics().items()}


def sql_literal(rx: str) -> str:
    """Spark SQL string literals process backslash escapes, so every backslash is doubled."""
    assert "'" not in rx
    return "'" + rx.replace("\\", "\\\\") + "'"


def render() -> str:
    cases = ",\n".join(f"    CASE WHEN c.text RLIKE {sql_literal(rx)} THEN '{name}' END" for name, rx in topics().items())
    return f"""-- GENERATED by gen_topic_view.py from ctgov-discovery/scripts/04_mine_terms.py CATEGORIES (+ FIXES). Do not edit.
-- One-Trial test, step 4: Criterion topic view over our Postgres `criterion` table (registered as datasource
-- `trialmatch` in db/zetaris_register.sql). One Criterion can have several topics; topics only route.

-- Container (once per name; skip if it exists).
-- OUTCOME: NOT RUN
CREATE SCHEMASTORE CONTAINER trialmatch_views;

-- OUTCOME: NOT RUN
CREATE SCHEMASTORE VIEW criterion_topic WITH CONTAINER trialmatch_views AS
SELECT c.id AS criterion_id, c.nct_id, c.eligibility_hash, c.kind, c.ordinal, topic
FROM trialmatch.criterion c
LATERAL VIEW explode(array(
{cases}
)) AS topic
WHERE topic IS NOT NULL;

-- Expect for NCT07680790 (same as 07_one_trial.py, minus labs_organ_function on ordinal 2):
-- 1 diagnosis_histology, stage_grade_risk, relapsed_refractory, prior_treatment
-- 2 biomarker_genetic, prior_treatment
-- 3 measurable_disease
-- 4 performance_status
-- 5 stage_grade_risk, cns_brain_mets
-- 6 stage_grade_risk, comorbidity_infection, concomitant_meds
-- 7 comorbidity_infection
-- 8 (none)
-- OUTCOME: NOT RUN
SELECT ordinal, concat_ws(', ', collect_list(topic)) AS topics
FROM trialmatch_views.criterion_topic
WHERE nct_id = 'NCT07680790'
GROUP BY ordinal ORDER BY ordinal;

-- Teardown:
-- DROP VIEW trialmatch_views.criterion_topic;
"""


if __name__ == "__main__":
    (HERE / "02_criterion_topic.sql").write_text(render())
    print(f"wrote {HERE / '02_criterion_topic.sql'} ({len(topics())} topics)")
